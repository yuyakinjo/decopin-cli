/**
 * `.decopin/` に生成するコード (ADR 5 の emit)。
 *
 * ルートごとに動的 import にするのは、実行しないコマンドの
 * モジュール本体を「評価しない」ため (ADR 12。パースは全量走る)。
 */
import { relative } from 'node:path';

import type { EffectVerdicts } from '../types/effects.ts';
import type { Route } from './scanner.ts';

const HEADER = `// Generated by decopin build. Edits are overwritten on the next build.
`;

/** import 指定子に使えるよう、常に posix 区切りで相対パスにする */
function toSpecifier(outDir: string, file: string): string {
  const path = relative(outDir, file).split('\\').join('/');
  return path.startsWith('.') ? path : `./${path}`;
}

/** ルートに書き出す規約ファイル。Phase が進むごとに増える */
const WIRED_FILES = [
  'command',
  'argv',
  'stdin',
  'data',
  'output',
  'shell',
] as const;

function importer(outDir: string, file: string): string {
  return `() => import(${JSON.stringify(toSpecifier(outDir, file))})`;
}

export interface RoutesInput {
  routes: Route[];
  /** ルート名 → error.tsx の並び。**近い順** (自分 → 親 → ...) */
  errorChains?: Map<string, string[]>;
  /** ルート名 → not-found.tsx の並び。**近い順** (ADR 30) */
  notFoundChains?: Map<string, string[]>;
  /** ルート名 → layout.tsx の並び (外側から順)。ADR 7 */
  layoutChains?: Map<string, string[]>;
  /** ルート名 → middleware.tsx の並び (外側から順)。ADR 13 */
  middlewareChains?: Map<string, string[]>;
  /** app/global-error.tsx */
  globalError?: string;
  /** ディレクトリ (ルートは空文字) → help.tsx */
  helpFiles?: Map<string, string>;
  /** app/not-found.tsx */
  notFound?: string;
  /** app/env.tsx */
  env?: string;
  /** app/version.tsx */
  version?: string;
  /** ルート名 → 副作用の判定 (ADR 32)。MCP の annotations が読む (ADR 33) */
  effects?: Map<string, EffectVerdicts>;
}

export function generateRoutes(input: RoutesInput, outDir: string): string {
  const entries = input.routes.map((route) => {
    if (route.files.command === undefined) {
      throw new Error(`Route "${route.name}" has no command file`);
    }
    const loaders = WIRED_FILES.flatMap((kind) => {
      const file = route.files[kind];
      if (file === undefined) return [];
      return [`    ${kind}: ${importer(outDir, file)},`];
    });

    const chains: [string, string[]][] = [
      ['errors', input.errorChains?.get(route.name) ?? []],
      ['notFounds', input.notFoundChains?.get(route.name) ?? []],
      ['layouts', input.layoutChains?.get(route.name) ?? []],
      ['middlewares', input.middlewareChains?.get(route.name) ?? []],
    ];
    for (const [key, files] of chains) {
      if (files.length === 0) continue;
      const list = files
        .map((file) => `      ${importer(outDir, file)},`)
        .join('\n');
      loaders.push(`    ${key}: [\n${list}\n    ],`);
    }

    // 判定は実行時に計算できない (ソースを歩くのはビルド時だけ) ので、
    // 表に値として焼き込む
    const verdicts = input.effects?.get(route.name);
    if (verdicts !== undefined) {
      loaders.push(`    effects: ${JSON.stringify(verdicts)},`);
    }

    return `  ${JSON.stringify(route.name)}: {\n${loaders.join('\n')}\n  },`;
  });

  const single = (name: string, file: string | undefined): string =>
    file === undefined
      ? `export const ${name} = undefined;`
      : `export const ${name} = ${importer(outDir, file)};`;

  // help はディレクトリ単位なので、コマンド表とは別のマップにする
  const helps = [...(input.helpFiles ?? new Map())]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(
      ([dir, file]) => `  ${JSON.stringify(dir)}: ${importer(outDir, file)},`
    )
    .join('\n');

  // entry.ts が必ず import するので、空でも export は出す
  const helpsBody = helps === '' ? '{}' : `{\n${helps}\n}`;

  return `${HEADER}
import type { RouteTable } from 'decopin-cli';

export const routes = {
${entries.join('\n')}
} satisfies RouteTable;

export const helps: Record<string, () => Promise<unknown>> = ${helpsBody};

${single('globalError', input.globalError)}
${single('notFound', input.notFound)}
${single('envFile', input.env)}
${single('versionFile', input.version)}
`;
}

export function generateEntry(program: string, bin: string): string {
  return `${HEADER}
import { run } from 'decopin-cli';
import {
  envFile,
  globalError,
  helps,
  notFound,
  routes,
  versionFile,
} from './routes.ts';

// Ctrl+C is 128+2 = 130. Without a handler Bun would exit with 0
process.on('SIGINT', () => process.exit(130));

// No top-level await on purpose: bun build --compile --bytecode refuses a
// module that has one, and bytecode is worth about a fifth of startup
// (11.0ms vs 13.8ms measured). run() reports failures itself, so the
// rejection path here only catches bugs in the framework.
run(routes, {
  program: ${JSON.stringify(program)},
  bin: ${JSON.stringify(bin)},
  globalError,
  notFound,
  helps,
  envFile,
  versionFile,
}).then(
  (code) => process.exit(code),
  (error) => {
    process.stderr.write(String(error) + '\\n');
    process.exit(1);
  }
);
`;
}
