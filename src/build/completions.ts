/**
 * zsh 補完シムの生成 (ADR 21)。
 *
 * ここで焼き込むのはコマンドの構成ではなく「CLI に聞きに行く」手順だけ。
 * 候補は Tab のたびに `<bin> __complete` (src/runtime/complete.ts) が返すので、
 * コマンドを足してもこのファイルは変わらず、zsh の compdump を無効化する
 * 必要がない。反映されるのは bundle が更新されたとき (`decopin build`)。
 * `decopin dev` は bundle を作り直さないので、dev 中の変更は build するまで
 * 補完には出ない。
 */

import { binaryName } from '../runtime/shell.ts';

export { binaryName };

/**
 * 実際に打つコマンド名を解決する。help に出す `program` (package.json の
 * `name`) とは別物で、コマンド名は `bin` のキーが決める。`bin` が文字列の
 * ときは npm の規則でパッケージ名 (スコープを除く) がコマンド名になる
 */
export async function resolveBinaryName(program: string): Promise<string> {
  try {
    const json = (await Bun.file('package.json').json()) as { bin?: unknown };
    const bin = json.bin;
    if (bin !== null && typeof bin === 'object') {
      const key = Object.keys(bin)[0];
      if (key !== undefined) return key;
    }
  } catch {
    // package.json が無い / 読めないなら name に落ちる
  }
  return binaryName(program);
}

/** 補完シムのファイル名。zsh の規約で `_<コマンド名>` */
export function completionFileName(program: string): string {
  return `_${binaryName(program)}`;
}

/** zsh の関数名に使えない文字を潰す */
function functionName(program: string): string {
  return `_${binaryName(program).replace(/[^A-Za-z0-9_-]/g, '_')}`;
}

/**
 * `$fpath` の通ったディレクトリに置くと `compinit` が拾う。
 * 1 行目の `#compdef` が「このコマンドの補完はこの関数」という宣言
 */
export function generateZshCompletion(program: string): string {
  const bin = binaryName(program);
  const fn = functionName(program);
  return `#compdef ${bin}
# Generated by decopin build. Edits are overwritten on the next build.
#
# This is a thin shim: candidates come from the CLI itself via
# \`${bin} __complete\`, one per line as \`value<TAB>description\`.
# The shim does not depend on the command tree, so rebuilding the CLI
# is enough -- this file never needs to be regenerated or re-sourced.

${fn}() {
  local -a lines candidates
  local output line value description
  output="$(${bin} __complete -- "\${(@)words[2,CURRENT]}" 2>/dev/null)" || return 1
  lines=("\${(@f)output}")
  for line in "\${lines[@]}"; do
    [[ -z "$line" ]] && continue
    value="\${line%%$'\\t'*}"
    description="\${line#*$'\\t'}"
    if [[ "$description" == "$line" ]]; then
      candidates+=("\${value//:/\\\\:}")
    else
      candidates+=("\${value//:/\\\\:}:\${description}")
    fi
  done
  if (( \${#candidates[@]} == 0 )); then
    _files
    return
  fi
  _describe 'values' candidates
}

if [[ "\${funcstack[1]}" == "${fn}" ]]; then
  ${fn} "$@"
else
  compdef ${fn} ${bin}
fi
`;
}
