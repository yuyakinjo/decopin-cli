/**
 * 宣言から `.decopin/types.d.ts` を書く (ADR 9 の emit)。
 *
 * `command.tsx` は `CommandProps<'hello'>` でこの型を引く。
 * JSX 式は型引数を運べない (ADR 9) ので、型はここを通してしか届かない。
 */
import type {
  ArgSpec,
  ArgvSpec,
  EnvSpec,
  OptionSpec,
  StdinSpec,
} from '../declaration/spec.ts';
import type { TypeNode } from '../declaration/type-node.ts';
import type { EvaluatedRoute } from './evaluator.ts';
import {
  schemaToTypeText,
  type SchemaTypeResult,
  type UnsupportedNode,
} from './schema-introspect.ts';
import { quoteKey, wrapUnion } from './ts-text.ts';

const HEADER = `// Generated by decopin build / decopin dev.
// Edits are overwritten on the next build.
`;

/** 型宣言を TypeScript の型に直す */
export function toTypeText(type: TypeNode): string {
  switch (type.kind) {
    case 'string':
      return 'string';
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'enum':
      return type.values.map((value) => JSON.stringify(value)).join(' | ');
    case 'date':
      return 'Date';
    case 'instant':
      return 'Temporal.Instant';
    case 'plainDate':
      return 'Temporal.PlainDate';
    case 'array':
      return `${wrap(type.item)}[]`;
    case 'object': {
      const fields = type.fields.map((field) => {
        const optional = field.required || field.defaultValue !== undefined;
        return `${quoteKey(field.name)}${optional ? '' : '?'}: ${toTypeText(
          field.type
        )}`;
      });
      return `{ ${fields.join('; ')} }`;
    }
    case 'oneOf':
      return type.options.map(wrap).join(' | ');
    case 'custom':
      // as が無ければ型は分からないので unknown (ADR 9)
      return type.as ?? 'unknown';
  }
}

/** union を配列にするときは括弧が必要 */
function wrap(type: TypeNode): string {
  return wrapUnion(toTypeText(type));
}

/** 省略できるキーは `?` を付ける (既定値があれば必ず入るので付けない) */
function member(
  name: string,
  type: string,
  required: boolean,
  defaultValue: unknown
): string {
  const always = required || defaultValue !== undefined;
  return `${quoteKey(name)}${always ? '' : '?'}: ${type}`;
}

function argMember(arg: ArgSpec): string {
  const type = arg.variadic ? `${wrap(arg.type)}[]` : toTypeText(arg.type);
  return member(arg.name, type, arg.required, arg.defaultValue);
}

function optionMember(option: OptionSpec): string {
  return member(
    option.name,
    toTypeText(option.type),
    option.required,
    option.defaultValue
  );
}

/** stdin.tsx の宣言から、command が受け取る値の型を決める (ADR 2) */
export function stdinType(stdin: StdinSpec | undefined): SchemaTypeResult {
  if (stdin === undefined) return { text: 'never', unsupported: [] };

  const introspected =
    stdin.mode === 'json' && stdin.schema !== undefined
      ? schemaToTypeText(stdin.schema)
      : undefined;

  const base =
    introspected !== undefined
      ? introspected.text
      : stdin.mode === 'text'
        ? 'string'
        : stdin.mode === 'lines'
          ? 'string[]'
          : stdin.type === undefined
            ? 'unknown'
            : toTypeText(stdin.type);

  // required でなければ、端末実行時に undefined が渡る。
  // unknown はどんな値も含むので、足しても意味が増えない
  const text =
    stdin.required || base === 'unknown' ? base : `${base} | undefined`;
  return { text, unsupported: introspected?.unsupported ?? [] };
}

/** 型テキストだけが欲しい場合 */
export function stdinTypeText(stdin: StdinSpec | undefined): string {
  return stdinType(stdin).text;
}

function shape(spec: ArgvSpec, stdin: StdinSpec | undefined): string {
  const args =
    spec.args.length === 0
      ? '{}'
      : `{ ${spec.args.map(argMember).join('; ')} }`;
  const options =
    spec.options.length === 0
      ? '{}'
      : `{ ${spec.options.map(optionMember).join('; ')} }`;
  return `{ args: ${args}; options: ${options}; stdin: ${stdinTypeText(
    stdin
  )} }`;
}

/** `env.tsx` の宣言から EnvVars の型を作る */
function envShape(env: EnvSpec | undefined): string {
  if (env === undefined || env.vars.length === 0) return '';
  const members = env.vars.map((declared) => {
    const always = declared.required || declared.defaultValue !== undefined;
    return `    ${quoteKey(declared.name)}${always ? '' : '?'}: ${toTypeText(
      declared.type
    )};`;
  });
  return `\n  interface EnvVars {\n${members.join('\n')}\n  }\n`;
}

export interface TypesResult {
  text: string;
  /** schema の内省で unknown に落ちた箇所 (ADR 9) */
  unsupported: Array<{ file: string; nodes: UnsupportedNode[] }>;
}

export function generateTypes(
  evaluated: EvaluatedRoute[],
  env?: EnvSpec
): TypesResult {
  const unsupported: TypesResult['unsupported'] = [];
  const entries = evaluated
    .map(({ route, spec, stdin }) => {
      const nodes = stdinType(stdin).unsupported;
      const file = route.files.stdin;
      if (nodes.length > 0 && file !== undefined) {
        unsupported.push({ file, nodes });
      }
      return `    ${quoteName(route.name)}: ${shape(spec, stdin)};`;
    })
    .join('\n');

  const text = `${HEADER}
import 'decopin-cli';

declare module 'decopin-cli' {
  interface Routes {
${entries}
  }
${envShape(env)}}
`;
  return { text, unsupported };
}

/** ルートコマンドは空文字なので、常に引用符付きで書く */
function quoteName(name: string): string {
  return JSON.stringify(name);
}
