/**
 * 宣言から `.decopin/types.d.ts` を書く (ADR 9 の emit)。
 *
 * `cmd.tsx` は `CommandProps<'hello'>` でこの型を引く。
 * JSX 式は型引数を運べない (ADR 9) ので、型はここを通してしか届かない。
 */
import type { ArgvSpec } from '../../features/conventions/argv/spec.ts';
import { argvTypeText } from '../../features/conventions/argv/type-emitter.ts';
import { dataTypeText } from '../../features/conventions/data/type-emitter.ts';
import type { StdinSpec } from '../../features/conventions/stdin/spec.ts';
import {
  stdinType,
  stdinTypeText,
} from '../../features/conventions/stdin/type-emitter.ts';
import type { EnvSpec } from '../../features/root-only/env/spec.ts';
import { envShape } from '../../features/root-only/env/type-emitter.ts';
import type { EvaluatedRoute } from './evaluator.ts';
import type { UnsupportedNode } from './schema-introspect.ts';

export { toTypeText } from '../types/type-text.ts';
export { dataTypeText } from '../../features/conventions/data/type-emitter.ts';
export {
  stdinType,
  stdinTypeText,
} from '../../features/conventions/stdin/type-emitter.ts';

const HEADER = `// Generated by decopin build / decopin dev.
// Edits are overwritten on the next build.
`;

function shape(
  spec: ArgvSpec,
  stdin: StdinSpec | undefined,
  data: string
): string {
  return `{ ${argvTypeText(spec)}; stdin: ${stdinTypeText(
    stdin
  )}; data: ${data} }`;
}

export interface TypesResult {
  text: string;
  /** schema の内省で unknown に落ちた箇所 (ADR 9) */
  unsupported: Array<{ file: string; nodes: UnsupportedNode[] }>;
}

export function generateTypes(
  evaluated: EvaluatedRoute[],
  env?: EnvSpec,
  workDir = '.decopin'
): TypesResult {
  const unsupported: TypesResult['unsupported'] = [];
  const entries = evaluated
    .map(({ route, spec, stdin, output }) => {
      const nodes = stdinType(stdin).unsupported;
      const file = route.files.stdin;
      if (nodes.length > 0 && file !== undefined) {
        unsupported.push({ file, nodes });
      }
      const data = dataTypeText(route.files.data, workDir, output);
      return `    ${quoteName(route.name)}: ${shape(spec, stdin, data)};`;
    })
    .join('\n');

  const text = `${HEADER}
import 'decopin-cli';

declare module 'decopin-cli' {
  interface Routes {
${entries}
  }
${envShape(env)}}
`;
  return { text, unsupported };
}

/** ルートコマンドは空文字なので、常に引用符付きで書く */
function quoteName(name: string): string {
  return JSON.stringify(name);
}
