import { describe, expect, test } from 'bun:test';

import {
  generateEntry,
  generateRoutes,
  loadedFiles,
} from '../../../src/core/build/codegen.ts';
import type { RoutesInput } from '../../../src/core/build/codegen.ts';
import type { Route } from '../../../src/core/build/scanner.ts';
import { createNotFoundChains } from '../../../src/features/inherited/not-found/build.ts';

const routes: Route[] = [
  {
    name: 'hello',
    dir: 'hello',
    files: { cmd: 'app/hello/cmd.tsx' },
  },
  {
    name: 'user/create',
    dir: 'user/create',
    files: { cmd: 'app/user/create/cmd.tsx' },
  },
];

describe('generateRoutes', () => {
  test('ルートごとに動的 import を並べる', () => {
    const code = generateRoutes({ routes }, '.decopin');
    expect(code).toContain('cmd: () => import("../app/hello/cmd.tsx"),');
    expect(code).toContain('cmd: () => import("../app/user/create/cmd.tsx"),');
  });

  test('argv.tsx があれば一緒に配線する', () => {
    const code = generateRoutes(
      {
        routes: [
          {
            name: 'hello',
            dir: 'hello',
            files: {
              cmd: 'app/hello/cmd.tsx',
              argv: 'app/hello/argv.tsx',
            },
          },
        ],
      },
      '.decopin'
    );
    expect(code).toContain('argv: () => import("../app/hello/argv.tsx"),');
  });

  test('argv.tsx がなければ command だけを書く', () => {
    const code = generateRoutes({ routes }, '.decopin');
    expect(code).not.toContain('argv:');
  });

  test('生成物であることを先頭に書く', () => {
    expect(generateRoutes({ routes }, '.decopin')).toContain(
      'Generated by decopin build'
    );
  });

  test('cmd のないルートは作れない', () => {
    expect(() =>
      generateRoutes(
        { routes: [{ name: 'x', dir: 'x', files: {} }] },
        '.decopin'
      )
    ).toThrow(/has no cmd file/);
  });

  test('埋め込む値の危険な文字を Unicode エスケープする', () => {
    const unsafe = '</script>\u2028\u2029"';
    const code = generateRoutes(
      {
        routes: [
          {
            name: unsafe,
            dir: unsafe,
            files: { cmd: `app/${unsafe}/cmd.tsx` },
          },
        ],
        helpFiles: new Map([[unsafe, `app/${unsafe}/help.tsx`]]),
      },
      '.decopin'
    );

    expect(code).not.toContain('</script>');
    expect(code).not.toContain('\u2028');
    expect(code).not.toContain('\u2029');
    expect(code).toContain('\\u003C/script\\u003E\\u2028\\u2029');
    const routeName = code.match(/^  (.+): \{$/m)?.[1];
    expect(routeName).toBeDefined();
    expect(JSON.parse(routeName ?? '')).toBe(unsafe);
    const commandSpecifier = code.match(
      /^    cmd: \(\) => import\((.+)\),$/m
    )?.[1];
    expect(commandSpecifier).toBeDefined();
    expect(JSON.parse(commandSpecifier ?? '')).toBe(`../app/${unsafe}/cmd.tsx`);
  });
});

describe('generateEntry', () => {
  test('program の危険な文字を Unicode エスケープする', () => {
    const unsafe = '</script>\u2028\u2029"\\';
    const code = generateEntry(unsafe, unsafe);

    expect(code).not.toContain('</script>');
    expect(code).not.toContain('\u2028');
    expect(code).not.toContain('\u2029');
    expect(code).toContain('program: "\\u003C/script\\u003E\\u2028\\u2029');
    const program = code.match(/^  program: (.+),$/m)?.[1];
    expect(program).toBeDefined();
    expect(JSON.parse(program ?? '')).toBe(unsafe);
  });
});

describe('generateRoutes — error.tsx の連鎖', () => {
  test('近い順に error.tsx を並べる', () => {
    const code = generateRoutes(
      {
        routes,
        errorChains: new Map([
          ['user/create', ['app/user/create/error.tsx', 'app/user/error.tsx']],
        ]),
      },
      '.decopin'
    );
    const errors = code.slice(code.indexOf('errors: ['));
    expect(errors.indexOf('user/create/error.tsx')).toBeLessThan(
      errors.indexOf('user/error.tsx')
    );
  });

  test('error.tsx が無いルートには errors を書かない', () => {
    const code = generateRoutes({ routes }, '.decopin');
    expect(code).not.toContain('errors:');
  });

  test('global-error.tsx を別に export する', () => {
    expect(
      generateRoutes(
        { routes, globalError: 'app/global-error.tsx' },
        '.decopin'
      )
    ).toContain(
      'export const globalError = () => import("../app/global-error.tsx");'
    );
  });

  test('global-error.tsx が無ければ undefined', () => {
    expect(generateRoutes({ routes }, '.decopin')).toContain(
      'export const globalError = undefined;'
    );
  });
});

describe('generateRoutes — not-found.tsx の連鎖', () => {
  test('近い順に not-found.tsx を並べる', () => {
    const notFoundChains = createNotFoundChains(
      routes,
      new Map([
        ['user/create', { 'not-found': 'app/user/create/not-found.tsx' }],
        ['user', { 'not-found': 'app/user/not-found.tsx' }],
      ])
    );
    const code = generateRoutes(
      {
        routes,
        notFoundChains,
      },
      '.decopin'
    );
    const notFounds = code.slice(code.indexOf('notFounds: ['));
    expect(notFounds.indexOf('user/create/not-found.tsx')).toBeLessThan(
      notFounds.indexOf('user/not-found.tsx')
    );
  });

  test('not-found.tsx が無いルートには notFounds を書かない', () => {
    const code = generateRoutes({ routes }, '.decopin');
    expect(code).not.toContain('notFounds:');
  });
});

describe('generateRoutes — layout / middleware の連鎖', () => {
  test('layout は外側から順に並べる', () => {
    const code = generateRoutes(
      {
        routes,
        layoutChains: new Map([
          ['user/create', ['app/layout.tsx', 'app/user/layout.tsx']],
        ]),
      },
      '.decopin'
    );
    const layouts = code.slice(code.indexOf('layouts: ['));
    expect(layouts.indexOf('"../app/layout.tsx"')).toBeLessThan(
      layouts.indexOf('"../app/user/layout.tsx"')
    );
  });

  test('middleware も外側から順に並べる', () => {
    const code = generateRoutes(
      {
        routes,
        middlewareChains: new Map([
          ['hello', ['app/middleware.tsx', 'app/hello/middleware.tsx']],
        ]),
      },
      '.decopin'
    );
    const middlewares = code.slice(code.indexOf('middlewares: ['));
    expect(middlewares.indexOf('"../app/middleware.tsx"')).toBeLessThan(
      middlewares.indexOf('"../app/hello/middleware.tsx"')
    );
  });

  test('該当が無ければ書かない', () => {
    const code = generateRoutes({ routes }, '.decopin');
    expect(code).not.toContain('layouts:');
    expect(code).not.toContain('middlewares:');
  });
});

// entry.ts / routes.ts の形そのものは test/contract/build.test.ts にある

/**
 * 副作用の解析 (ADR 32) は `loadedFiles` を入口にする。表に書いたのに入口に
 * 無いファイルは、**実行されるのに解析されない**。`app/env.tsx` がそうで、
 * そこで書き込んでも MCP には読み取り専用と出ていた (GHSA-mj3j-jwf5-4xcc)
 */
describe('loadedFiles', () => {
  const input: RoutesInput = {
    routes: [
      {
        name: 'hello',
        dir: 'hello',
        files: {
          cmd: 'app/hello/cmd.tsx',
          argv: 'app/hello/argv.tsx',
          stdin: 'app/hello/stdin.tsx',
          data: 'app/hello/data.tsx',
          output: 'app/hello/output.tsx',
          shell: 'app/hello/shell.tsx',
          complete: 'app/hello/complete.tsx',
          help: 'app/hello/help.tsx',
        },
      },
      {
        name: 'user/create',
        dir: 'user/create',
        files: { cmd: 'app/user/create/cmd.tsx' },
      },
    ],
    errorChains: new Map([['user/create', ['app/user/error.tsx']]]),
    notFoundChains: new Map([['user/create', ['app/user/not-found.tsx']]]),
    layoutChains: new Map([['hello', ['app/layout.tsx']]]),
    middlewareChains: new Map([['hello', ['app/middleware.tsx']]]),
    helpFiles: new Map([['hello', 'app/hello/help.tsx']]),
    globalError: 'app/global-error.tsx',
    notFound: 'app/not-found.tsx',
    env: 'app/env.tsx',
    version: 'app/version.tsx',
  };

  test('表に書いたファイルは、どれかのコマンドの入口に必ず入っている', () => {
    const code = generateRoutes(input, '.decopin');
    const wired = [...code.matchAll(/import\("\.\.\/([^"]+)"\)/g)].map(
      (match) => match[1] as string
    );
    // 取りこぼしなく拾えていること (規約ファイルが増えたらここも増える)
    expect(wired).toHaveLength(17);
    const reachable = new Set(
      input.routes.flatMap((route) => loadedFiles(input, route))
    );
    expect(wired.filter((file) => !reachable.has(file))).toEqual([]);
  });

  test('ルート共通のファイルは、全部のコマンドの入口に入る', () => {
    for (const route of input.routes) {
      expect(loadedFiles(input, route)).toEqual(
        expect.arrayContaining([
          'app/global-error.tsx',
          'app/not-found.tsx',
          'app/env.tsx',
          'app/version.tsx',
        ])
      );
    }
  });

  test('ほかのコマンドのファイルは入らない', () => {
    const files = loadedFiles(input, input.routes[1] as Route);
    expect(files).toContain('app/user/create/cmd.tsx');
    expect(files).toContain('app/user/error.tsx');
    expect(files).not.toContain('app/hello/cmd.tsx');
    expect(files).not.toContain('app/layout.tsx');
  });
});
